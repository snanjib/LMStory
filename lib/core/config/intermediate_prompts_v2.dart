4. 角色心理活动的原文描述

【叙事时间标注（必须遵守）】
- 每个事件都应标注其叙事时间（如"来公寓第一天"），便于LLM理解时间线
- 若对话中无明确时间信号，根据事件顺序推断（如"早期""中期""近期"）
- 叙事时间必须是绝对时间（基于故事起点），禁止使用相对时间（如"昨天""刚才"）

【长度控制】
- 摘要应在 500-2000 字之间
- 信息密度高：每个句子都应承载关键信息，避免空话
- 按"事件时间线 → 角色出场 → 当前阶段"的结构组织

【输出要求】
- 直接输出摘要正文，不要输出 JSON、标记、前言或额外说明
- 用清晰的段落组织（可用换行分隔不同部分）
- 用简洁的陈述句，不要用对话体或描写体
- 使用与对话相同的语言（中文对话用中文摘要）

【正例】
来公寓第一天：主角林晓搬入阳光公寓302室，遇到房东王阿姨（热心，50多岁，提及公寓"有些年头了"）。
来公寓第二天：遇到邻居A（302室对面，男性，性格冷漠，自我介绍叫陈默）。主角听到走廊异常声响。
来公寓第三天：主角在地下室发现旧照片，照片中人物穿着年代不符。陈默看到主角拿照片后反应异常。
来公寓第五天：主角质问陈默，陈默透露公寓曾发生"那件事"，但拒绝详述。

角色出场：
- 林晓（主角）：刚搬入公寓的年轻人，对周围事物好奇
- 王阿姨（房东）：热心，似乎知道公寓历史但不愿多谈
- 陈默（邻居）：冷漠，隐藏秘密，与"那件事"有关

当前阶段：故事处于发展期，主角已发现异常线索（旧照片、声响、陈默的反应），尚未揭开真相。

【反例（禁止）】
- 把每轮对话都复述一遍（太详细，丢失宏观骨架）
- 只写"主角和邻居互动了几次"（太抽象，没有具体事件）
- 包含角色台词原文（"陈默说：'你不该来这里的'"）
- 包含环境描写原文（"走廊的灯光忽明忽暗，空气中弥漫着陈旧的气味"）''';

