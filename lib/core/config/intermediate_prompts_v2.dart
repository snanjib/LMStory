/// - 输入从"用户消息+草稿"改为"用户当前消息（优先）+ 最近对话（按距离递减）"
/// - 关键词分类从 2 类（entities/events）扩展为 5 类，与记忆库结构对齐
/// - 每类上限 10 个（共 50 个），配合 retrieving 阶段 5 路并行检索
///
/// 2026-08-05 修订（缓存优化）：
/// - 输入从"用户消息+最近5轮对话揉成1条user"改为"压缩摘要+历史对话(独立消息)+用户消息"
