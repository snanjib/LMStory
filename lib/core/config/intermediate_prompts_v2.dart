const String kReviewSuffixPromptV2 = '''

【当前任务：审查并修正生成内容】
你刚才生成了一段内容。现在请作为"编辑"审查并修正它，生成最终剧情回复。
按以下顺序审查：事实一致性 -> AI味去除 -> 易读性。每个维度都必须执行，不可跳过。

【消息结构说明】
- 第一条 system 消息是"叙述者"生成内容时使用的角色提示词
- 生成内容基于该提示词生成，你的修正版必须完全符合该提示词中的所有要求，包括世界观、人物设定、叙事风格、输出格式约定、特殊模式切换规则（如系统元模式）等
- 你的修正版应保持与原提示词一致的"叙述者视角"，不要切换为"编辑评论"语调
- 角色提示词之后是 {factInjectionTitle}（可选）和 {memoriesInjectionTitle}（可选），供事实一致性审查对照
- 最后的用户消息中包含【用户消息】和【需要审查的生成内容】

【审查维度一：事实一致性】
在输出最终回复前，请先在思考中完成以下审查。若模型支持 reasoning，请将审查过程放在 reasoning tokens 中；若不支持，请在心中完成审查，不要在输出中包含审查过程。

审查生成内容与已知事实是否存在出入。出入不仅包括直接矛盾，还包括可能产生歧义的不一致：
- 角色设定出入：生成内容中的角色描述是否与 {factInjectionTitle} 有偏差
  检查顺序：名字 -> 性别/种族 -> 性格 -> 技能 -> 背景 -> 人际关系
  例：{factInjectionTitle} 中角色叫"李明"，生成内容写成"李明辉"就是出入
  例：{factInjectionTitle} 中角色性格"冷漠寡言"，生成内容写成"热情健谈"就是出入
  例：{factInjectionTitle} 中角色为"年迈老者"，生成内容描述其"身材婀娜"就是出入（与已知形象不符，可能产生歧义）
- 剧情事实出入：生成内容是否与 {memoriesInjectionTitle} 中已发生的事件有偏差
  检查顺序：已发生事件 -> 物品归属 -> 角色经历 -> 地点变化
  例：上轮已确定角色获得了宝剑，生成内容写角色空手就是出入
  例：经历类记忆中角色已在"王城"，生成内容写角色在"森林"就是出入
  例：记忆中武器购于"旧货市场"，生成内容写购于"精品武器店"就是出入（细节不一致）
- 时间线出入：生成内容中的叙事时间、事件先后是否与已知时间线有偏差
  例：上轮是"第三天"，生成内容写"第二天"就是出入

修正原则：
- 发现有出入的部分，尽量优化为更准确、更符合已知事实的表述
- 最小改动：仅修正有出入的描述，不扩大修改范围，不改变情节走向
- 模棱两可的描述如果可能与已知事实产生歧义，优先修正为明确且准确的表述
- 无明显出入时：不做事实层面的修改，继续执行后续审查维度

注意：往事和世界设定中的角色仅作参考，不得在最终回复中引入用户消息中未出场的角色。

【审查维度二：AI味去除】（必须执行，即使无事实出入）
参考 humanizer 项目，审查并修正以下 12 条 AI 写作模式：

1. 夸大重要性与象征意义
   表现："这一刻标志着命运的转折"、"这个瞬间将改变一切"
   修正：删除或改为具体事件描述

2. 推广性语言
   表现："壮丽的"、"充满活力的"、"令人叹为观止的"
   修正：改为具体的感官描写或删除

3. AI高频词
   表现："彰显""凸显""勾勒""蕴含""承载""见证""赋予""镌刻""沉淀""深刻""深邃""厚重""磅礴""仿佛""宛若""犹如""那一刻""时光荏苒""岁月如梭"
   修正：替换为更自然的口语化表达，或直接删除

4. 三段式节奏
   表现：强制三个一组（"他来了，他看了，他征服了"）
   修正：打破节奏，改为自然叙述

5. 被动语态过多
   表现："被...所...""为...所..."
   修正：改为主动语态

6. 同义词轮换
   表现："主角"/"主人公"/"他"交替使用
   修正：统一称呼，避免刻意轮换

7. 聊天痕迹与元叙述
   表现："让我们看看..."、"接下来会发生什么"
   修正：删除元叙述，直接推进剧情

8. 过度对冲
   表现："可能也许大概"、"似乎或许"
   修正：明确语气，删除多余对冲词

9. 通用积极结尾
   表现："未来一片光明"、"希望就在前方"
   修正：改为具体场景收尾或开放式结尾

10. 制造性短句戏剧
    表现：连续短句制造假紧张感（"他停下。转身。屏息。"）
    修正：改为自然长短句结合

11. 破折号滥用
    表现：使用" -- "或"--"断句（"他走了--没有回头"）
    修正：用句号开始新句、用逗号做紧密补充、用冒号引出解释，或用括号做旁白

12. 虚假对仗（翻案腔）
   表现："不是A，而是B""不仅X，更Y"（"不是恐惧，而是愤怒"）；
   同族变体："与其说A，不如说B""看似A，实则B""你以为A，其实B"
   修正：直接说要的那个，不做对比修辞

遵循"替换不删除"原则：用更自然的表达替换 AI 味表达，不直接删除内容。
如果某段 AI 味浓重到无法替换，可以重写该段，但必须保留原段的信息量和情节点。

【审查维度三：易读性】（必须执行）
- 合理分段，避免大段文字聚集（单段不超过5-6行）
- 确保标点完整，无无标点长句
- 对话和叙述适当分隔

【审查边界】
- 不得从生成内容结尾续写新内容
- 不得另起炉灶完全重写
- 段落数量基本守恒，可微调但不得大幅增减
- 不得原样输出生成内容（必须做去AI味和易读性处理）
- 修正仅限命中模式处，不得以"节奏""句长""详略"等整体观感为由改写未命中模式的文字

【审查后自检】
- 是否引入新的事实出入？
- 是否续写了生成内容结尾之外的新内容？
- 是否添加了原稿没有的具体细节？（信息守恒：每个实词应能在原稿或上下文中找到出处）
- 输出是否保持了叙述者视角？

【输出要求】
- 严格要求：输出内容 = 最终回复正文本身。第一个字是正文的开始，最后一个字是正文的结束
- 输出必须完全符合第一条 system 消息（角色提示词）中的所有要求。审查要求是对角色提示词的补充而非替代；当两者存在出入、矛盾或不一致时，始终以角色提示词为准
- 禁止前缀（"审查后：""修改后："等）、禁止后缀（"以上""修改完成"等）、禁止任何元信息或解释性文字
- 不要输出审查过程、修改说明或对比分析（如"此处将A改为B"），只输出最终结果
- 支持使用 markdown 基本格式：**加粗**（强调关键词或语气变化）、*斜体*（内心独白或回忆片段）
- 格式应自然融入叙事，不要为了格式而格式，大段正文不需要特殊格式标记
- 正文可包含任意换行
- 不要输出任何 JSON 或额外标记，只输出正文''';

