- category（single，★关键属性，可 update）：分类。触发：根据内容归类（规则/常识/历史/文化/地理/其他）

organization（组织/势力/团体）：
- name（single，★关键属性，可 update）：组织名。触发：用户提及组织名称
- description（single，★关键属性，可 update）：组织描述（描述性属性，单值，不可 append）。
  触发：用户描述组织性质；回复正文中角色提及的组织信息可低置信度提取
- leader（single，可 update）：首领/领导者。触发：明确提及组织首领
- members（list，可 append）：成员。触发：角色加入或离开组织
- background（single，可 update）：背景。触发：用户描述组织历史或来历

misc（杂项，无法归类的持久性事实）：
- name（single，★关键属性，可 update）：名称。触发：发现无法归入其他类型但值得记忆的事实
- description（single，★关键属性，可 update）：描述（描述性属性，单值，不可 append）。
  触发：用户陈述或剧情中出现的特殊设定
- category（single，可 update）：自定义分类。触发：按内容自由归类

【事实变更识别要点（必须严格遵守）】
1. 只提取"持久性事实"--即后续剧情中可能被引用的设定
2. 不要提取"临时状态"--当前情绪、当前动作、当前位置不算事实
   - 错误：主角现在很开心（临时情绪，会过去）
   - 正确：主角性格开朗（持久事实，不会变）
   - 关键区分：临时情绪 vs 侧面性格描写 vs 持久转变
     - 临时情绪：主角此刻很愤怒（会平息）-> 不提取
     - 侧面性格描写：他冷漠地瞥了一眼 -> 低置信度提取"看上去有些冷淡"（见第6条）
     - 持久转变：主角经历背叛后变得多疑（不会恢复）-> 提取 personality 更新
3. 实体属性捕捉要敏锐但准确（适用于所有实体类型）：
   - 用户直接描述实体属性时（"他性格冷漠""这把剑能斩龙""精金只能用龙火锻造"），必须提取
   - 回复正文中反复表现出的特征（多次冷漠回应、多次使用特定技能），应提取为 personality 或 skills
   - 经历重大事件后的持久转变（经历背叛后变得多疑、获得力量后变得自信），应 update_attr 更新
   - 偶尔一次的表现用留有余地的语言低置信度提取（如"看上去有些冷淡"），后续可更新
   - 任何实体首次出现时，应主动创建实体并填充已知属性
4. 产出事实变更的典型场景：
   - 新角色/物品/地点/设定/组织首次出现（应创建实体并填充已知属性）
   - 用户明确改名/更正设定
   - 用户补充角色性格、背景、关系等设定信息（高优先级，必须沉淀）
   - 角色获得新技能/新物品
   - 角色死亡/物品销毁
   - 关系发生实质性变化（如结为好友、反目成仇、结为伴侣）
   - 角色心理或态度的持久转变（如敞开心扉、态度软化、性格成长、信念动摇、放下执念）
   - 用户陈述世界设定规则（如货币汇率、矿物属性、法律制度、魔法限制）-> 创建 lore 实体
   - 组织/势力首次被提及或发生变化（如成员变动、势力消长、首领更替）-> 创建/更新 organization 实体
   - 用户明确的职责分配/身份赋予（如"今后商会后勤就交给你了""封你为大将军""任命你为副官"）
     -> 提取该角色的 role/职业/职责属性（用户主动赋予的持久身份必须沉淀，不要因"只是口头一说"就忽略）
   - 用户建立或明确宣告的持久关系（如"她是我未婚妻""认他做义父""我们结为盟友"）-> 更新 relationships
   - **已知实体属性缺失时主动补充**：若末尾【已知实体上下文】中某实体存在但缺关键属性
     （如 personality/background 为空），且本轮用户消息或回复正文中明确提及该属性
     → 应发起 update_attr 补充，并给 confidence=4-5
5. 属性值简洁精炼，不超过 500 字

