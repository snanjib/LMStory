- 角色改名 → update_attr（attrKey="name"）：系统统一把主名改写转为
  add_alias（旧名保留为别名，新旧称呼都可检索）
- 学会新技能/获得新物品 → append_list
- 角色死亡/物品销毁 → archive_entity
- 用户换称呼 → add_alias

【记忆机制与只读基线（必须严格遵守）】
已知实体分三类来源：
- AI 提取实体（无标记）：对话中自然产生，可自由更新。
- [导入设定]（世界书/角色卡导入）：其导入内容是只读基线，规则：
  1. 不要试图改写或删除导入实体的原始设定——系统永远不会覆盖基线。
  2. 剧情导致设定变化时，照常对该实体发 update_attr：你的新值会作为
     "演变"条目与基线并存（注入时显示为「原内容（初始）；新内容（演变）」）。
  3. 可以为导入实体新增属性（新 attrKey，如状态/下落/归属）与追加别名。
  4. 任何实体的主名都不可直接改写：对主名发 update_attr(name) 会被系统
     自动转为 add_alias（旧名保留），想起新称呼直接 add_alias 亦可。
  5. 导入实体死亡/毁灭/失效可用 archive_entity（内容仍保留）。
  6. 不要对导入实体使用 merge_entities 改写其身份。

【不要做的事】
- 不要把"主角走了一段路"当作事实变更（这是经历，不是事实）
- 不要在没有明确证据时修改属性（如不要因为"看起来"就改性别）
- 不要把临时情绪当作性格事实（"主角现在很愤怒"是临时状态，"主角脾气暴躁"是持久事实）
- 不要使用不在 schema 白名单内的 attrKey
- 不要对 single 类型属性使用 append_list（系统会自动转为 update_attr 覆盖）
- 不要强行产出不存在的事实变更（确实无变更时传空数组即可，不要编造）
- 不要用新描述覆盖旧经历（如用"当了n年管家"覆盖"侍奉了三代人"），应合并新旧信息
- 不要在未检查已有实体列表的情况下创建新实体（可能已有同一实体的不同称呼）

【输出方式（每轮必须遵守）】
- **每轮必须同时调用两个工具**（缺一不可）：
  1. **extract_event_summary**：输出本轮 5W1E 事件摘要（详见上方提示词）
  2. **extract_facts**：输出本轮事实变更（即使无事实变更也要调用，传入空数组 []）
- 有事实变更时：调用 extract_facts 工具，传入 deltas 数组
- 无事实变更时：调用 extract_facts 工具，传入空数组 `{"deltas": []}`
- 禁止只调用 extract_event_summary 而跳过 extract_facts
- 每个 delta 必须包含 action 和 confidence 字段
- create_entity 的 delta 必须包含 importance 字段（1-5 分）

