const String kExtractKeywordsToolPrompt = '''

【当前任务：提取检索关键词】
请根据下方【用户当前消息】的语义意图，结合上方近几轮对话的语境，提取能从
记忆库检索到相关信息的词。对话历史用于补充语境、揣测用户本轮想检索什么；
关键词本身服务于当前消息的检索需求（去匹配记忆库的存储格式），不要直接把
历史里的词整句复制过来。

【检索原理：为什么分类不同、格式要求不同】
本系统使用两种检索引擎，对不同类别的关键词采用不同匹配方式：
- FTS5 全文精确匹配：在记忆库中逐字搜索，关键词必须与记忆库中存储的文本完全一致才能命中。因此需要具体名词（如"李逍遥"能匹配，"主角"不能匹配）。
- Vector 语义匹配：将关键词转为向量，在记忆库中寻找语义相似的记忆。需要语义丰富的动宾短语（如"师父传功"能匹配到"传授武功""教导法术"等语义相近的记忆，而"发生互动"语义太模糊，会匹配到大量无关记忆）。
理解这个原理后，你会明白：名词越具体，精确匹配越准确；短语语义越丰富，语义匹配越有效。
逆向思考——记忆库里的经历按 5W1E（when/where/who/what/significance）存储、
事实按实体属性存储。你的关键词要去匹配这些存储格式：具体名词用于命中实体名
（角色/地点/物品），动宾短语用于命中事件描述（谁做了什么）。

【关键词分类详解】
事实层实体 3 类（走 FTS5 精确匹配，必须是具体名词）：
- characters：角色名（含主角和 NPC）。有名字的用名字（"李逍遥""赵灵儿"），没有名字但被频繁提及的可用称谓（"师父""王阿姨"）。禁止用"主角""他""那个人"等代词或泛化称谓。
- items：关键物品/道具名。物理存在的具体物件（"七星剑""古碑""钥匙"）。禁止用"东西""物品""道具"等泛化词。
- locations：场景/地点名。具体的地理位置或场所（"蜀山""仙灵岛""地下室"）。禁止用"这里""那个地方""附近"等代词或泛化词。

经历层 2 类（走 Vector 语义匹配，必须是动宾短语）：
- actions：角色的具体动作/行为。动宾结构，描述角色在做什么（"斩妖""寻人""破解阵法""炼丹"）。禁止用"发生战斗""出现变化"等无主语的概括。
- plots：剧情事件/情节要点。动宾结构，描述发生了什么事件（"灵儿被掳走""获得七星剑""师父失踪"）。禁止用"剧情推进""出现转折"等抽象概括。

分类边界：
- 有名字的角色归 characters，无名字的背景角色（如"村民""士兵"）一般不提取，除非是频繁提及的称谓
- 天气/氛围不是物品也不是地点，不提取
- 角色的内心活动不算 action（"感到愤怒"不是动作，"摔门离去"是动作）
- 持续状态不算 plot（"正在修炼"不是事件，"突破境界"是事件）

