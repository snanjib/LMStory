/// 批量记忆提炼提示词（新增）
///
/// 由 `MemoryConsolidator` 使用，将若干条低重要性事件摘要合并为高重要性剧情节点记忆。
/// 触发时机：上下文 token 占用率超过 `ConsolidationConfig.triggerThreshold` 时，
/// 由 `IntermediateChatController._maybeConsolidateMemories` 异步调用。
///
/// 输入：用户消息中注入按时间顺序排列的低重要性记忆（含轮次/importance/summary/tags）。
/// 输出：纯 JSON `{"consolidated":[{summary,tags,importance}]}`，可为空数组。
///
/// 设计要点（避免大模型在相近轮次重复提取）：
/// - 合并同一场景/对象/因果链的多条摘要为一条剧情节点
/// - 合并后 importance 通常升至 3-5（达到存储门槛后建索引，可被检索）
/// - 无关联的摘要可独立保留并提升 importance
/// - 纯重复或无意义的摘要直接丢弃
const String kConsolidationPrompt = '''

【当前任务：合并低重要性记忆（JSON 格式）】
以下是若干条低重要性的事件摘要（按时间顺序排列）。请将相关的事件合并为高重要性的剧情节点记忆，使后续轮次可从记忆中检索到这些合并后的关键剧情。

【合并规则】
- 同一场景 / 同一对象 / 有因果关系的多条摘要 → 合并为一条
- 合并后的 summary 必须是"主语+动作+对象+后果"的剧情节点描述，突出变化与因果
- 合并后的 importance 通常升至 3-5（信息量更大）；无关联的摘要可独立保留并提升 importance
- 纯重复或无意义的摘要直接丢弃（不输出）
- tags 取合并后仍相关的 1-3 个标签

【输出要求】
- 必须输出一个合法的 JSON 对象，且只输出该 JSON 对象
- 输出的第一个字符必须是 {，最后一个字符必须是 }
