- 结构：{"consolidated":[{"summary":"合并后的剧情节点","tags":["标签1"],"importance":4}]}
- consolidated 数组可为空（无值得合并的记忆时输出 []）

【summary 写作要点】
- 好："勇者在后山发现古碑，碑文揭示其身世秘密"（突出变化与因果）
