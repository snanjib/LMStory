/// Simple mode spacing tokens.
///
/// Base unit: 4px. All values are multiples.
class LmSpacing {
  LmSpacing._();

  /// 2px — hairline gaps
  static const double s3xs = 2;

  /// 4px — tight inline spacing, icon-label gap
  static const double s2xs = 4;

  /// 6px — compact padding, chip internal
  static const double sXs = 6;

  /// 8px — standard inline, list item inner
  static const double sSm = 8;

  /// 12px — form field spacing, card inner vertical
  static const double sMd = 12;

  /// 16px — page margins, card padding, section gaps
  static const double sLg = 16;

  /// 24px — section dividers, prominent rhythm
  static const double sXl = 24;

  /// 32px — page-level separation
  static const double s2xl = 32;

  /// 48px — hero spacing, major section breaks
  static const double s3xl = 48;
}
