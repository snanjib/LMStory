/// Simple mode border radius tokens.
class LmRadius {
  LmRadius._();

  /// 4px — small badges, inline tags
  static const double rXs = 4;

  /// 8px — chips, small buttons
  static const double rSm = 8;

  /// 12px — input fields, list items
  static const double rMd = 12;

  /// 16px — cards, panels, bottom sheets
  static const double rLg = 16;

  /// 20px — large containers, modal
  static const double rXl = 20;

  /// 9999px — pills, avatar, capsule buttons
  static const double rFull = 9999;
}
